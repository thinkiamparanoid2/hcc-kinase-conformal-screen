"""The README's two generated tables must match results/metrics/.

The README claims no number in it is typed by hand. The two summary tables are
generated by scripts/make_readme_tables.py; this test is what makes that claim
enforceable, so a re-run that changes a metric cannot leave a stale README behind.
"""
import os
import subprocess
import sys

import pytest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO_ROOT, "scripts"))

make_readme_tables = pytest.importorskip("make_readme_tables")


@pytest.mark.parametrize("block", sorted(make_readme_tables.BLOCKS))
def test_readme_block_matches_metrics(block):
    readme = os.path.join(REPO_ROOT, "README.md")
    with open(readme, encoding="utf-8") as handle:
        text = handle.read().replace("\r\n", "\n")
    expected = make_readme_tables.rendered(block).strip()
    assert expected in text, (
        f"README's {block} block is stale or missing. Regenerate with:\n"
        f"    python scripts/make_readme_tables.py"
    )


def test_check_mode_passes_on_the_committed_readme():
    result = subprocess.run(
        [sys.executable, os.path.join(REPO_ROOT, "scripts", "make_readme_tables.py"), "--check"],
        capture_output=True, text=True, cwd=REPO_ROOT)
    assert result.returncode == 0, result.stdout + result.stderr
